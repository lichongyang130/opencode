/** 上一次为该卡生成的组合签名（防连续重复） */
const lastUsed = new Map<string, string>();

function pickFrom<T>(arr: T[], avoid?: T): T {
  if (arr.length <= 1) return arr[0];
  const candidates = arr.filter((x) => x !== avoid);
  const pool = candidates.length > 0 ? candidates : arr;
  return pool[Math.floor(Math.random() * pool.length)];
}

/**
 * 生成某卡的一条详细提示词。same 卡连续调用保证不同（组合签名防重）。
 * @param skillKey 技能 key（chat/docs/slides/image/research/video）
 * @param title     卡片标题
 * @param skillLabel 技能显示名
 */
export function buildDetailedPrompt(skillKey: string, title: string, skillLabel: string): string {
  // 界面技能 key（如 PPT 模板用 "ppt"）与生成器内部池统一（slides）
  const k = skillKey === "ppt" ? "slides" : skillKey;
  const pool = POOLS[k];
  const angles = CARD_ANGLES[k]?.[title];
  if (!pool || !angles || angles.length === 0) {
    // 兜底：无池数据时返回标题相关的一句话任务
    return `请帮我完成「${title}」：${skillLabel}相关的任务，请给出专业、完整、可直接使用的输出。`;
  }

  const key = `${skillKey}::${title}`;
  const last = lastUsed.get(key) ?? "";

  let angle = pickFrom(angles, undefined);
  let d1 = pickFrom(pool.details, undefined);
  let d2 = pickFrom(pool.details, d1);
  let tone = pickFrom(pool.tones, undefined);
  let output = pickFrom(pool.outputs, undefined);
  let signature = `${angle}|${d1}|${d2}|${tone}|${output}`;

  // 与上次相同则整体重抽一次（最多几次）
  let guard = 0;
  while (signature === last && guard < 6) {
    angle = pickFrom(angles, angle);
    d1 = pickFrom(pool.details, d1);
    d2 = pickFrom(pool.details, d1);
    tone = pickFrom(pool.tones, tone);
    output = pickFrom(pool.outputs, output);
    signature = `${angle}|${d1}|${d2}|${tone}|${output}`;
    guard += 1;
  }
  lastUsed.set(key, signature);

  return [
    `# 角色\n${pool.role}。`,
    `# 任务\n${angle}。`,
    `# 具体要求\n- ${d1}\n- ${d2}\n- ${tone}`,
    `# 输出\n${output}。`,
  ].join("\n");
}
